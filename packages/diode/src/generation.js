/**
 * Генерація й рекомбінація в самому збідненому шарі — другий механізм струму
 * поряд із дифузійним.
 *
 * Ідеальна формула Шоклі рахує лише носії, які продифундували крізь перехід.
 * Але всередині збідненого шару рухомих носіїв майже немає, і рівновага там
 * підтримується через пастки: пара або народжується (при зворотному зміщенні
 * її одразу розтягує поле — це струм), або рекомбінує (при прямому).
 *
 * Без цього доданка модель розходиться з тим, що студент виміряє насправді:
 *
 *  — зворотний струм кремнієвого діода пропорційний n_i, а НЕ n_i², тому він
 *    подвоюється на кожні 10 К, як і пише підручник, а не зростає вп'ятеро;
 *  — зворотна вітка не строго горизонтальна: W ~ √(V_bi − U), тому струм
 *    повільно росте як корінь із напруги — саме це видно на реальній ВАХ;
 *  — на прямій вітці цей механізм дає експоненту з n = 2, через що виміряний
 *    коефіцієнт ідеальності виходить не рівно 1, а залежить від того, яку
 *    ділянку взяв студент. Це і є головний зміст обробки результатів.
 */

import { Q, SI } from "./constants.js";
import { intrinsicConcentration } from "./intrinsic.js";
import { carrierLifetime } from "./doping.js";
import { depletion } from "./junction.js";

/**
 * Префактор генераційно-рекомбінаційного струму [А]:
 *
 *     I_г = q·n_i·W·A/(2τ)
 *
 * Ділення на 2τ — бо через пастку в середині забороненої зони пара
 * народжується вдвічі повільніше, ніж рекомбінує на краю.
 *
 * Ширина W береться при ЗОВНІШНІЙ напрузі `bias`, а не при напрузі на самому
 * переході. Різниця між ними — це спад на послідовному опорі, і він помітний
 * лише при великих прямих струмах, де цей механізм давно перекритий дифузією.
 * Взамін ми отримуємо величину, яка не залежить від шуканого струму, — і тому
 * розв'язувач лишається однопрохідною бісекцією без зовнішньої ітерації.
 */
export function generationCurrent({
  na,
  nd,
  temperature,
  area,
  bias = 0,
  material = SI,
}) {
  const ni = intrinsicConcentration(temperature, material);
  const { width } = depletion({ na, nd, temperature, bias, material });
  // Час життя визначає слабше легований бік: там пастки рідші, і саме він
  // задає, як довго пара живе, перш ніж рекомбінувати.
  const tau = carrierLifetime(Math.min(na, nd), material);
  return { igen: (Q * ni * width * area) / (2 * tau), ni, width, tau };
}
