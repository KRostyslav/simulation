/**
 * Зворотний пробій переходу.
 *
 * До певної напруги діод тримає — зворотний струм не залежить від напруги
 * і мізерний. Далі поле в збідненому шарі стає таким сильним, що народжує
 * носії саме собою, і струм зростає на порядки при майже незмінній напрузі.
 * Пробій НЕ є руйнуванням: якщо обмежити струм резистором, діод повернеться
 * в нормальний стан. Руйнує його не пробій, а перегрів.
 */

import { SI } from "./constants.js";
import { bandGap } from "./intrinsic.js";

/**
 * Напруга лавинного пробою різкого одностороннього переходу (емпірика Сзе):
 *
 *     V_проб ≈ 60·(E_g/1,1)^1,5·(N/10¹⁶)^−0,75  [В]
 *
 * N — легування СЛАБКІШОГО боку: збіднений шар росте саме туди, і саме там
 * набирається напруга. Тому сильніше леговані переходи пробиваються раніше:
 * шар вужчий, поле в ньому більше при тій самій напрузі.
 *
 * Контроль: кремній при 10¹⁶ дає 62 В, германій при тому самому легуванні —
 * 28 В (вужча зона — легше іонізувати), а кремній при 2,4·10¹⁷ — 5,7 В,
 * тобто звичайний стабілітрон.
 */
export function breakdownVoltage({ na, nd, material = SI, temperature = 300 }) {
  const lighter = Math.min(na, nd);
  const eg = bandGap(temperature, material);
  return 60 * (eg / 1.1) ** 1.5 * (lighter / 1e16) ** -0.75;
}

/**
 * Температурний коефіцієнт напруги пробою [В/К] — ознака, за якою
 * розрізняють два зовсім різні механізми.
 *
 * Нижче ≈4·E_g пробій тунельний (зенерівський): електрон просочується крізь
 * бар'єр, і нагрівання, звужуючи зону, лише полегшує це — напруга пробою
 * ПАДАЄ. Вище ≈6·E_g пробій лавинний: носій розганяється полем і вибиває
 * інші; нагрівання скорочує вільний пробіг, розігнатись важче — напруга
 * пробою РОСТЕ.
 *
 * Між ними коефіцієнт проходить через нуль. Для кремнію це приблизно 5,6 В —
 * і саме тому стабілітрони на 5,6 В найстабільніші за температурою.
 */
export function breakdownTempCoefficient(vbr, eg) {
  const x = Math.min(1, Math.max(0, (vbr - 4 * eg) / (2 * eg)));
  return (-4e-4 + x * 8e-4) * (vbr / 5.6);
}

/** Повний опис пробою для даного переходу. */
export function breakdownAt({ na, nd, temperature = 300, material = SI }) {
  const eg = bandGap(temperature, material);
  const vbr0 = breakdownVoltage({ na, nd, material, temperature });
  const tcv = breakdownTempCoefficient(vbr0, eg);
  const vbr = vbr0 + tcv * (temperature - 300);

  let kind = "змішаний";
  if (vbr0 < 4 * eg) kind = "тунельний";
  else if (vbr0 > 6 * eg) kind = "лавинний";

  return {
    vbr: Math.max(0.5, vbr),
    vbr0,
    kind,
    tcv,
    // Коліно: наскільки різко наростає струм за точкою пробою. 50 мВ на декаду —
    // типова крутість реального стабілітрона.
    knee: 0.05,
    ibr: 1e-6,
  };
}
