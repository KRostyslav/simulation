/**
 * Детермінований генератор випадкових чисел.
 *
 * Чому не Math.random(). Точка, записана студентом у таблицю, мусить лишатися
 * тією самою: при перемальовуванні графіка, при перемиканні вигляду, після
 * перезавантаження сторінки. Якби шум кидався щоразу наново, таблиця «пливла»
 * б у нього на очах, а розрахунок, зроблений уранці, не збігався б із тим,
 * що показує екран увечері. Тому кожне вимірювання отримує свій seed,
 * виведений із номера точки, і шум у ньому назавжди той самий.
 */

/**
 * mulberry32 — 32-бітний генератор, один множник і кілька зсувів.
 * Якості для навчального шуму більш ніж достатньо, а головне — він
 * відтворюваний до біта на будь-якій машині.
 */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Нормальний розподіл через перетворення Бокса–Мюллера.
 *
 * Саме нормальний, а не рівномірний: похибка приладу складається з багатьох
 * дрібних незалежних причин, і центральна гранична теорема робить її
 * гаусовою. Рівномірний шум мав би різкі межі, і студент, помітивши їх,
 * зробив би з цього хибний висновок про природу похибки.
 */
export function gaussian(rng) {
  // Нуль під логарифмом дав би −∞, тому нижню межу зсуваємо.
  const u = Math.max(rng(), 1e-12);
  const v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/** Seed із кількох цілих — щоб точка №7 при 320 К мала свій, але сталий шум. */
export function seedFrom(...parts) {
  let h = 2166136261;
  for (const part of parts) {
    h ^= Math.round(part * 1000) | 0;
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
