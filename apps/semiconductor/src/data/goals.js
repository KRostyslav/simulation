export const GOALS_BY_ID = Object.fromEntries(GOALS.map((goal) => [goal.id, goal]));

/** Які цілі виконані в цьому знімку. */
export function achievedGoals(snapshot) {
  return GOALS.filter((goal) => {
    try {
      return goal.check(snapshot);
    } catch {
      // Ціль іншого режиму може не знайти потрібних полів — це не помилка.
      return false;
    }
  }).map((goal) => goal.id);
}
