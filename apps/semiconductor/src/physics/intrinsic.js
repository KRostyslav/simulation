/**
 * Власна (внутрішня) провідність чистого кремнію.
 *
 * Ключова величина — n_i(T), кількість пар «електрон + дірка», які теплові
 * коливання ґратки встигають народити при даній температурі. Саме вона
 * пояснює головний факт теми: у напівпровідника опір при нагріванні падає,
 * а не росте, як у металу.
 */

import { K_EV, SI, T0 } from "./constants.js";

/** Тепловий потенціал kT/q [В]. При 300 К — класичні 0,02585 В. */
export function thermalVoltage(temperature) {
  return K_EV * temperature;
}

/** Ширина забороненої зони за Варшні [еВ]. Із нагріванням зона трохи вужчає. */
export function bandGap(temperature) {
  const { eg0, alpha, beta } = SI.varshni;
  return eg0 - (alpha * temperature * temperature) / (temperature + beta);
}

/**
 * Власна концентрація носіїв n_i(T) [см⁻³].
 *
 * Канонічна формула n_i = √(N_c·N_v)·exp(−Eg/2kT) із табличними N_c, N_v
 * і Eg = 1,12 еВ дає 6,7·10⁹ см⁻³, тоді як виміряне значення для кремнію —
 * 1,0·10¹⁰ см⁻³ (розбіжність походить від температурної залежності
 * ефективних мас, якої проста формула не враховує).
 *
 * Тому ми зберігаємо правильну функціональну форму — передекспонента ∝ T^{3/2}
 * і експонента зі справжньою Eg(T) — але прив'язуємо її до виміряного значення
 * в опорній точці 300 К. Учневі при цьому показуємо спрощений вигляд
 * n_i ~ exp(−Eg/2kT): саме він пояснює, чому нагрівання діє так різко.
 *
 * Контроль: n_i(600 К) ≈ 3,5·10¹⁵ см⁻³ — правильний порядок величини.
 */
export function intrinsicConcentration(temperature) {
  const ratio = temperature / T0;
  const exponent =
    bandGap(T0) / (2 * K_EV * T0) - bandGap(temperature) / (2 * K_EV * temperature);
  return SI.ni300 * ratio ** 1.5 * Math.exp(exponent);
}

/**
 * Температура, при якій власна концентрація зрівнюється із заданою
 * концентрацією домішки. Вище неї легування вже нічого не вирішує —
 * кристал знову поводиться як власний напівпровідник.
 *
 * Шукаємо бісекцією: n_i(T) монотонно зростає, тому корінь єдиний.
 * Аналітично його не виразити — Eg(T) сама залежить від T.
 *
 * Межа max = 700 К збігається з верхом температурного регулятора. Це не
 * технічне обмеження, а зміст відповіді: підказка «нагрій до T» має сенс
 * лише тоді, коли гравець справді може туди дійти. Для N ≳ 2·10¹⁶
 * повертаємо null — при доступних температурах домішка так і лишиться
 * головним джерелом носіїв.
 */
export function crossoverTemperature(concentration, { min = 100, max = 700 } = {}) {
  if (!(concentration > 0)) return null;
  if (intrinsicConcentration(min) >= concentration) return min;
  if (intrinsicConcentration(max) <= concentration) return null; // недосяжно регулятором

  let lo = min;
  let hi = max;
  for (let i = 0; i < 80; i += 1) {
    const mid = (lo + hi) / 2;
    if (intrinsicConcentration(mid) < concentration) lo = mid;
    else hi = mid;
  }
  return (lo + hi) / 2;
}
