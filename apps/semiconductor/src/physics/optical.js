/**
 * Фотопровідність: світло як другий, крім тепла, спосіб розірвати зв'язок.
 *
 * Фотон із енергією більшою за Eg = 1,12 еВ (це довжина хвилі коротша
 * за 1100 нм, тобто все видиме світло) вибиває електрон із ковалентного
 * зв'язку. Народжується пара «електрон + дірка» — рівно так само, як від
 * нагрівання, але без нагрівання. Саме на цьому працює фоторезистор.
 */

import { carrierLifetime } from "./doping.js";

export { diffusionLength } from "@edu/diode";

/**
 * Темп генерації пар [см⁻³·с⁻¹] при освітленості в «сонцях».
 *
 * Калібрування: сонячний спектр AM1.5 дає близько 2,7·10¹⁷ фотонів/(см²·с)
 * з енергією понад Eg. Вони поглинаються у приповерхневому шарі товщиною
 * приблизно 10 мкм = 10⁻³ см, звідки об'ємний темп ≈ 2,7·10²⁰ см⁻³·с⁻¹.
 * Округлено до 2,5·10²⁰.
 */
export const GENERATION_PER_SUN = 2.5e20;

export function generationRate(suns) {
  return GENERATION_PER_SUN * Math.max(0, suns);
}

/**
 * Надлишкова концентрація Δn = Δp = G·τ [см⁻³].
 *
 * Стаціонарний стан: скільки пар за секунду народжується, стільки ж
 * рекомбінує. Тому чим довше живе носій, тим більше їх встигає накопичитись —
 * і тим сильніше світло змінює опір. У сильно легованому кристалі τ мале,
 * і фотопровідність майже непомітна на тлі домішкових носіїв.
 */
export function excessCarriers({ suns, doping }) {
  const tau = carrierLifetime(doping);
  const g = generationRate(suns);
  return { excess: g * tau, tau, generation: g };
}

